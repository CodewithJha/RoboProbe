/**
 * Design-token model and CSS renderer (doc 13 §1.1–1.3).
 *
 * `tokens.json` is the single source of truth; `web/scripts/gen-tokens.ts` renders it to `tokens.css` with
 * {@link renderTokensCss} and copies it to the backend report theme. Keeping the renderer here lets the
 * unit tests assert that the committed CSS is exactly what the JSON produces.
 */

/** Colour themes defined by the token file. `system` follows `prefers-color-scheme`. */
export const THEMES = ['light', 'dark'] as const;
export type ThemeName = (typeof THEMES)[number];

/** CSS custom property name → value. */
export type TokenGroup = Readonly<Record<string, string>>;

/** Parsed token file: one group per theme plus theme-independent groups (font, space, …). */
export interface DesignTokens {
  readonly themes: Readonly<Record<ThemeName, TokenGroup>>;
  readonly shared: Readonly<Record<string, TokenGroup>>;
}

const CUSTOM_PROPERTY = /^--[a-z0-9]+(?:-[a-z0-9]+)*$/;
const THEME_ATTRIBUTE = 'data-theme';
const INDENT = '  ';
const HEADER =
  '/* Generated by web/scripts/gen-tokens.ts from src/styles/tokens.json; do not edit by hand. */';

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function parseGroup(name: string, value: unknown): TokenGroup {
  if (!isRecord(value)) {
    throw new Error(`Token group '${name}' must be an object`);
  }
  const group: Record<string, string> = {};
  for (const [key, entry] of Object.entries(value)) {
    if (!CUSTOM_PROPERTY.test(key)) {
      throw new Error(`Token '${name}.${key}' is not a kebab-case CSS custom property`);
    }
    if (typeof entry !== 'string' || entry.trim() === '') {
      throw new Error(`Token '${name}.${key}' must be a non-empty string`);
    }
    group[key] = entry;
  }
  return group;
}

/** Validates raw JSON into {@link DesignTokens}; themes must define the same token names. */
export function parseTokens(raw: unknown): DesignTokens {
  if (!isRecord(raw)) {
    throw new Error('Token file must be a JSON object');
  }
  const { light, dark, ...rest } = raw;
  const themes = { light: parseGroup('light', light), dark: parseGroup('dark', dark) };
  const lightKeys = Object.keys(themes.light).sort().join();
  if (lightKeys !== Object.keys(themes.dark).sort().join()) {
    throw new Error('Themes light and dark must define the same tokens');
  }
  const shared: Record<string, TokenGroup> = {};
  const seen = new Set(Object.keys(themes.light));
  for (const [name, value] of Object.entries(rest)) {
    const group = parseGroup(name, value);
    for (const key of Object.keys(group)) {
      if (seen.has(key)) {
        throw new Error(`Token '${key}' is defined more than once`);
      }
      seen.add(key);
    }
    shared[name] = group;
  }
  return { themes, shared };
}

function declarations(group: TokenGroup, depth: number): string[] {
  const pad = INDENT.repeat(depth);
  return Object.entries(group).map(([key, value]) => `${pad}${key}: ${value};`);
}

function rule(selector: string, body: string[], depth = 0): string[] {
  const pad = INDENT.repeat(depth);
  return [`${pad}${selector} {`, ...body, `${pad}}`];
}

function themeBody(tokens: DesignTokens, theme: ThemeName, depth: number): string[] {
  return [
    `${INDENT.repeat(depth)}color-scheme: ${theme};`,
    '',
    ...declarations(tokens.themes[theme], depth),
  ];
}

/**
 * Renders the token CSS. Light is the default; dark applies when `data-theme="dark"` is set or, with no
 * explicit choice, when the OS prefers a dark scheme.
 */
export function renderTokensCss(tokens: DesignTokens): string {
  const selector = (theme: ThemeName): string => `:root[${THEME_ATTRIBUTE}='${theme}']`;
  const sharedBody = Object.entries(tokens.shared).flatMap(([name, group], index) => [
    ...(index === 0 ? [] : ['']),
    `${INDENT}/* ${name} */`,
    ...declarations(group, 1),
  ]);
  const blocks = [
    rule(':root', sharedBody),
    rule(`:root,\n${selector('light')}`, themeBody(tokens, 'light', 1)),
    rule(
      '@media (prefers-color-scheme: dark)',
      rule(`:root:not([${THEME_ATTRIBUTE}='light'])`, themeBody(tokens, 'dark', 2), 1),
    ),
    rule(selector('dark'), themeBody(tokens, 'dark', 1)),
  ];
  return [HEADER, ...blocks.map((block) => block.join('\n'))].join('\n\n') + '\n';
}
