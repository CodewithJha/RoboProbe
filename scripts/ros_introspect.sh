#!/usr/bin/env bash
# Capture ROS/Gazebo topic, param and frame names for T-091 evidence (docs/10 §3).
# Run inside the T-090 image after sourcing ROS and starting headless TB4+Nav2 (see docs/evidence/T-091).
set -euo pipefail

OUTPUT="${1:-docs/evidence/T-091/capture}"
TIMEOUT="${INTROSPECT_TIMEOUT_S:-150}"
START_X="${INTROSPECT_START_X:-2.12}"
START_Y="${INTROSPECT_START_Y:--21.30}"
YAW="${INTROSPECT_YAW:-1.57}"
GAZEBO="${GAZEBO:-1}"

if ! command -v ros2 >/dev/null 2>&1; then
  echo "ros2 not found; source /opt/ros/jazzy/setup.bash or use spikes/T-090 image" >&2
  exit 2
fi

mkdir -p "${OUTPUT}"

versions="${OUTPUT}/versions.txt"
dpkg-query -W 'ros-jazzy-*' 2>/dev/null | sort >"${versions}" || true

if [[ "${GAZEBO}" == "1" ]]; then
  launch_log="${OUTPUT}/launch.log"
  sim_share="$(ros2 pkg prefix nav2_minimal_tb4_sim)/share/nav2_minimal_tb4_sim"
  nav_share="$(ros2 pkg prefix nav2_bringup)/share/nav2_bringup"
  trap '[[ -n "${launch_pid:-}" ]] && kill -INT "${launch_pid}" 2>/dev/null || true' EXIT
  ros2 launch nav2_bringup tb4_simulation_launch.py \
    headless:=True use_rviz:=False \
    world:="${sim_share}/worlds/warehouse.sdf" \
    map:="${nav_share}/maps/warehouse.yaml" \
    x_pose:="${START_X}" y_pose:="${START_Y}" yaw:="${YAW}" \
    >"${launch_log}" 2>&1 &
  launch_pid=$!
  deadline=$((SECONDS + TIMEOUT))
  until ros2 lifecycle get /controller_server 2>/dev/null | grep -q "active \[3\]"; do
    if (( SECONDS > deadline )); then
      echo "timed out waiting for Nav2 (${TIMEOUT}s)" >&2
      exit 1
    fi
    sleep 2
  done
  sleep 3
fi

ros2 topic list -t | sort >"${OUTPUT}/ros2_topic_list.txt"
ros2 node list | sort >"${OUTPUT}/ros2_node_list.txt"
{
  echo "# controller_server enable_stamped_cmd_vel"
  ros2 param get /controller_server enable_stamped_cmd_vel 2>/dev/null || true
  echo "# controller_server use_sim_time"
  ros2 param get /controller_server use_sim_time 2>/dev/null || true
} >"${OUTPUT}/nav2_controller_flags.txt"

for node in controller_server velocity_smoother local_costmap global_costmap amcl bt_navigator; do
  if ros2 node list 2>/dev/null | grep -q "${node}"; then
    ros2 param dump "/${node}" >"${OUTPUT}/param_dump_${node}.yaml" 2>/dev/null || true
  fi
done

for topic in /scan /cmd_vel /odom /amcl_pose /rgbd_camera/depth_image; do
  if ros2 topic list 2>/dev/null | grep -Fx "${topic}"; then
    ros2 topic info -v "${topic}" >"${OUTPUT}/topic_info${topic//\//_}.txt" 2>/dev/null || true
  fi
done

if command -v ros2 >/dev/null && ros2 run tf2_tools view_frames 2>/dev/null; then
  mv -f frames.pdf frames.yaml "${OUTPUT}/" 2>/dev/null || true
fi

if command -v gz >/dev/null; then
  gz topic -l | sort >"${OUTPUT}/gz_topic_list.txt" || true
fi

xacro_path="$(ros2 pkg prefix nav2_minimal_tb4_description)/share/nav2_minimal_tb4_description/urdf/standard/turtlebot4.urdf.xacro"
{
  echo "xacro=${xacro_path}"
  grep -E 'rplidar_z_offset|base_link_z_offset|shell_z_offset' "${xacro_path}" 2>/dev/null || true
} >"${OUTPUT}/tb4_lidar_offsets.txt"

cat >"${OUTPUT}/README.txt" <<EOF
Generated by scripts/ros_introspect.sh at $(date -u +"%Y-%m-%dT%H:%M:%SZ")
Commit topics.yaml values when they match this capture.
EOF

echo "Wrote evidence to ${OUTPUT}"