"""Vendor the shared numerical modules for ROS and verify their source digests."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

_MODULES = ("geometry", "perturbation")
_HEADER = "# Generated by scripts/vendor_geometry.py. Edit the backend source.\n"
_IMPORTS = re.compile(r"^(from\s+|import\s+)roboprobe\.(geometry|perturbation)(?=[.\s]|$)", re.M)
_TRACE_MODULES = {
    "backends/trace_io.py": "trace_io.py",
    "core/errors.py": "trace_errors.py",
    "core/types/enums.py": "trace_enums.py",
    "core/types/trace.py": "trace.py",
}
_TRACE_IMPORTS = {
    "from roboprobe.core import errors": "from roboprobe_ros._vendor import trace_errors as errors",
    "from roboprobe.core.types import JsonValue": "from pydantic import JsonValue",
    "from roboprobe.core.types import Trace": "from roboprobe_ros._vendor.trace import Trace",
    "from roboprobe.core.types.enums import NavStatus": (
        "from roboprobe_ros._vendor.trace_enums import NavStatus"
    ),
}


def vendor(root: Path, *, check: bool) -> tuple[str, ...]:
    """Write or verify the generated Python modules and deterministic manifest."""
    source = root / "backend/src/roboprobe"
    destination = root / "ros_ws/src/roboprobe_ros/roboprobe_ros/_vendor"
    expected: dict[Path, str] = {}
    hashes: dict[str, str] = {}
    for package in _MODULES:
        for file in sorted((source / package).glob("*.py")):
            data = file.read_bytes()
            relative = file.relative_to(source)
            hashes[relative.as_posix()] = hashlib.sha256(data).hexdigest()
            expected[destination / relative] = _HEADER + _IMPORTS.sub(
                r"\1roboprobe_ros._vendor.\2", data.decode("utf-8")
            )

    for module, filename in _TRACE_MODULES.items():
        data = (source / module).read_bytes()
        hashes[module] = hashlib.sha256(data).hexdigest()
        content = data.decode("utf-8")
        for backend_import, vendor_import in _TRACE_IMPORTS.items():
            content = content.replace(backend_import, vendor_import)
        expected[destination / filename] = _HEADER + content

    expected[destination / "manifest.json"] = json.dumps(hashes, indent=2, sort_keys=True) + "\n"
    stale = {
        path
        for package in _MODULES
        for path in (destination / package).glob("*.py")
        if path not in expected
    }
    if check:
        changed = {
            path
            for path, content in expected.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        }
        return tuple(sorted(path.relative_to(root).as_posix() for path in stale | changed))

    for path in sorted(stale):
        if path.read_text(encoding="utf-8").startswith(_HEADER):
            path.unlink()
        else:
            msg = f"unexpected non-generated module {path.relative_to(root)}"
            raise ValueError(msg)
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return ()


def main() -> int:
    """Run against the current checkout from any working directory."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    drift = vendor(Path(__file__).resolve().parents[1], check=parser.parse_args().check)
    if drift:
        print("Regenerate changed ROS vendor files with python3 scripts/vendor_geometry.py")
        print("\n".join(drift))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
