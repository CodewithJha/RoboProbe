#!/usr/bin/env python3
"""Generate the configuration reference from the settings models (docs/27, NFR-CFG-003).

Renders, from ``roboprobe.core.settings.RoboProbeSettings``:

* the docs/27 §4.1-§4.10 tables between ``<!-- BEGIN GENERATED: config-tables -->`` and
  ``<!-- END GENERATED -->`` (hand-written prose outside the markers is preserved);
* ``.env.example`` (every variable commented out with its default);
* ``roboprobe.example.toml`` (every key commented out under its table header).

Usage (from the repository root): ``make config-docs`` / ``make config-docs-check``, or
``uv run --directory backend python ../scripts/gen_config_docs.py [--check]``.
``--check`` writes nothing and exits 1 with a unified diff when any file is stale.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
import textwrap
import types
from collections.abc import Callable, Iterator, Sequence
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from pydantic import BaseModel, SecretStr
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from roboprobe.core.settings import ENV_ALIASES, RoboProbeSettings

__all__ = [
    "BEGIN_MARKER",
    "END_MARKER",
    "SECTIONS",
    "FieldDoc",
    "iter_fields",
    "main",
    "render_env",
    "render_tables",
    "render_toml",
    "replace_block",
]

REPO_ROOT = Path(__file__).resolve().parents[1]
DOC_FILE = Path("docs/27-configuration-reference.md")
ENV_FILE = Path(".env.example")
TOML_FILE = Path("roboprobe.example.toml")

BEGIN_MARKER = "<!-- BEGIN GENERATED: config-tables -->"
END_MARKER = "<!-- END GENERATED -->"
COMMENT_WIDTH = 100
"""Wrap width of comments in the generated templates (ruff line length)."""
DOC_DEFAULT_KEY = "doc_default"
"""``json_schema_extra`` key overriding the rendered default (e.g. host-dependent defaults)."""

NO_DEFAULT = "\N{EN DASH}"
"""Table cell for settings without a default."""
ROOT_GROUP = "core"
"""``.env.example`` group name for root-level scalars such as ``env``."""
ENV_PREFIX = RoboProbeSettings.model_config.get("env_prefix", "")
ENV_DELIMITER = RoboProbeSettings.model_config.get("env_nested_delimiter") or "__"

SECTIONS: Sequence[tuple[str, Sequence[str]]] = (
    ("4.1 Core & database", ("env", "database")),
    ("4.2 Storage", ("storage",)),
    ("4.3 API", ("api",)),
    ("4.4 Runner (orchestrator) & worker", ("runner", "worker")),
    ("4.5 Backends", ("backends",)),
    ("4.6 Oracles (`oracles.*`, defaults for campaigns) — see 08 §4", ("oracles",)),
    ("4.7 Selection defaults (`selection.*`) — see 07 §6.3", ("selection",)),
    ("4.8 Analysis & risk", ("analysis", "risk")),
    ("4.9 Experiments", ("experiments",)),
    ("4.10 Logging & observability", ("logging", "observability")),
)
"""docs/27 §4 headings and the root fields each one documents (every root field exactly once)."""

# Compose-level variables (docs/27 §4.12) are read by docker/compose.yaml, not by the settings
# models, so they are appended to .env.example verbatim.
COMPOSE_VARIABLES: Sequence[tuple[str, str, str]] = (
    ("ROBOPROBE_IMAGE_TAG", "dev", "Image tag of the RoboProbe containers."),
    ("ROBOPROBE_API_PORT", "8000", "Host port published for the API."),
    ("ROBOPROBE_WEB_PORT", "8080", "Host port published for the dashboard."),
    ("ROBOPROBE_DB_NAME", "roboprobe", "PostgreSQL database name."),
    ("ROBOPROBE_DB_USER", "roboprobe", "PostgreSQL user name."),
    ("ROBOPROBE_DB_PORT", "5432", "Loopback host port for Postgres (dev profile only)."),
    ("ROBOPROBE_K2D_REPLICAS", "2", "Number of kinematic2d worker containers."),
)

ENV_HEADER = """\
# RoboProbe environment template — GENERATED by scripts/gen_config_docs.py; do not edit by hand.
# Copy to .env (git-ignored) and uncomment only what you need (docs/27).
# Variables use the ROBOPROBE_ prefix with "__" as the nested delimiter, e.g.
#   ROBOPROBE_RUNNER__TICK_INTERVAL_S=0.5  ->  runner.tick_interval_s
# Values shown are the defaults. Never put real secrets here: use the files in
# ROBOPROBE_SECRETS_DIR (default /run/secrets: db_password, api_token) instead.
# ROBOPROBE_CONFIG_FILE and ROBOPROBE_SECRETS_DIR are read from the process environment only.
"""

TOML_HEADER = """\
# RoboProbe configuration file template — GENERATED by scripts/gen_config_docs.py; do not edit.
# Copy to ./roboprobe.toml (git-ignored) or point ROBOPROBE_CONFIG_FILE at your copy, then
# uncomment the keys you want to change. Precedence, highest first: CLI flags > ROBOPROBE_* env
# vars > .env > this file > secret files > defaults (docs/27 §2).
# Never put secrets here (docs/27 §6): use env vars or secret files for SecretStr keys.
"""


@dataclass(frozen=True, slots=True)
class FieldDoc:
    """One documented leaf setting."""

    path: tuple[str, ...]
    type_name: str
    default: Any
    description: str
    secret: bool
    """True for secret-typed fields without a default: templates never show a value."""

    @property
    def key(self) -> str:
        """Dotted key, e.g. ``oracles.loc.e_max``."""
        return ".".join(self.path)

    @property
    def env_var(self) -> str:
        """Canonical environment variable name."""
        return (ENV_PREFIX + ENV_DELIMITER.join(self.path)).upper()


def iter_fields(model: type[BaseModel], prefix: tuple[str, ...] = ()) -> Iterator[FieldDoc]:
    """Yield every leaf field of ``model`` depth-first, nested models expanded.

    Args:
        model: Settings model class.
        prefix: Path of ``model`` inside the root tree.

    Yields:
        Leaf documentation records in declaration order.
    """
    for name, info in model.model_fields.items():
        path = (*prefix, info.alias or name)
        nested = _nested_model(info.annotation)
        if nested is not None:
            yield from iter_fields(nested, path)
        else:
            yield FieldDoc(
                path=path,
                type_name=_type_name(info.annotation),
                default=_default(info),
                description=info.description or "",
                # A secret field with a default (e.g. a password-less DSN) is not secret itself.
                secret=_is_secret(info.annotation) and _default(info) is None,
            )


def _nested_model(annotation: Any) -> type[BaseModel] | None:  # noqa: ANN401
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    return None


def _is_secret(annotation: Any) -> bool:  # noqa: ANN401
    return SecretStr in (annotation, *get_args(annotation))


def _type_name(annotation: Any) -> str:  # noqa: ANN401
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Literal:
        return "enum: " + " / ".join(f"`{a}`" for a in args)
    if origin in (Union, types.UnionType):
        inner = [a for a in args if a is not type(None)]
        suffix = "?" if len(inner) < len(args) else ""
        return " / ".join(_type_name(a) for a in inner) + suffix
    if origin is tuple:
        return f"list[{_type_name(args[0])}]"
    if isinstance(annotation, type) and issubclass(annotation, Enum):
        return "enum: " + " / ".join(f"`{m.value}`" for m in annotation)
    return getattr(annotation, "__name__", str(annotation))


def _default(info: FieldInfo) -> Any:  # noqa: ANN401
    extra = info.json_schema_extra
    if isinstance(extra, dict) and DOC_DEFAULT_KEY in extra:
        return extra[DOC_DEFAULT_KEY]
    if info.default is not PydanticUndefined:
        value = info.default
    elif info.default_factory is not None:
        value = info.default_factory()  # type: ignore[call-arg]
    else:
        return None
    return value.get_secret_value() if isinstance(value, SecretStr) else value


def _plain(value: Any) -> Any:  # noqa: ANN401
    """Convert defaults to JSON/TOML-friendly primitives."""
    if isinstance(value, Path):
        return value.as_posix()
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, tuple | list):
        return [_plain(v) for v in value]
    return value


def _md_value(value: Any) -> str:  # noqa: ANN401
    if value is None:
        return NO_DEFAULT
    plain = _plain(value)
    text = plain if isinstance(plain, str) else json.dumps(plain)
    return f"`{text}`".replace("|", "\\|")


def _md(text: str) -> str:
    return text.replace("|", "\\|")


def render_tables(
    root: type[BaseModel] = RoboProbeSettings,
    sections: Sequence[tuple[str, Sequence[str]]] = SECTIONS,
) -> str:
    """Render the Markdown tables of docs/27 §4.

    Args:
        root: Root settings model.
        sections: ``(heading, root field names)`` pairs, in output order.

    Returns:
        Markdown with one ``###`` heading and table per section.

    Raises:
        ValueError: If a root field is missing from ``sections`` or listed twice.
    """
    listed = [name for _, names in sections for name in names]
    if sorted(listed) != sorted(root.model_fields):
        fields = sorted(root.model_fields)
        msg = f"sections must list every root field once: {sorted(listed)} vs {fields}"
        raise ValueError(msg)
    aliases = {".".join(path): name for name, path in ENV_ALIASES.items()}
    lines: list[str] = []
    for heading, names in sections:
        lines += [f"### {heading}", "", "| Key | Type | Default | Env var | Description |"]
        lines.append("|-----|------|---------|---------|-------------|")
        for name in names:
            for field in _fields_of(root, name):
                env = f"`{field.env_var}`"
                if field.key in aliases:
                    env += f" (alias `{aliases[field.key]}`)"
                lines.append(
                    f"| `{field.key}` | {_md(field.type_name)} | {_md_value(field.default)} "
                    f"| {env} | {_md(field.description)} |"
                )
        lines.append("")
    return "\n".join(lines)


def _fields_of(root: type[BaseModel], name: str) -> Iterator[FieldDoc]:
    info = root.model_fields[name]
    top = info.alias or name
    return (field for field in iter_fields(root) if field.path[0] == top)


def render_env(root: type[BaseModel] = RoboProbeSettings) -> str:
    """Render ``.env.example``: every variable commented out with its default."""
    lines = [ENV_HEADER.rstrip("\n")]
    current = ""
    for field in iter_fields(root):
        group = field.path[0] if len(field.path) > 1 else ROOT_GROUP
        if group != current:
            current = group
            lines += ["", f"# --- {current} ---"]
        value = "" if field.secret or field.default is None else _env_value(field.default)
        lines += [*_comment(field.description), f"# {field.env_var}={value}"]
    lines += ["", "# --- Docker Compose (docs/27 §4.12) ---"]
    for name, default, description in COMPOSE_VARIABLES:
        lines += [*_comment(description), f"# {name}={default}"]
    return "\n".join(lines) + "\n"


def _comment(text: str) -> list[str]:
    return textwrap.wrap(text, COMMENT_WIDTH, initial_indent="# ", subsequent_indent="# ")


def _env_value(value: Any) -> str:  # noqa: ANN401
    plain = _plain(value)
    if isinstance(plain, bool):
        return str(plain).lower()
    return plain if isinstance(plain, str) else json.dumps(plain)


def render_toml(root: type[BaseModel] = RoboProbeSettings) -> str:
    """Render ``roboprobe.example.toml``: table headers active, every key commented out."""
    lines = [TOML_HEADER.rstrip("\n")]
    for table, fields in _toml_tables(root):
        lines.append("")
        if table:
            lines.append(f"[{'.'.join(table)}]")
        for field in fields:
            lines += _comment(field.description)
            if field.secret:
                lines.append(f"# {field.path[-1]} = ...  (secret: set {field.env_var} instead)")
            elif field.default is None:
                lines.append(f"# {field.path[-1]} =  (unset by default)")
            else:
                lines.append(f"# {field.path[-1]} = {_toml_value(field.default)}")
    return "\n".join(lines) + "\n"


def _toml_tables(root: type[BaseModel]) -> list[tuple[tuple[str, ...], list[FieldDoc]]]:
    tables: dict[tuple[str, ...], list[FieldDoc]] = {}
    for field in iter_fields(root):
        tables.setdefault(field.path[:-1], []).append(field)
    return list(tables.items())


def _toml_value(value: Any) -> str:  # noqa: ANN401
    plain = _plain(value)
    if isinstance(plain, bool):
        return str(plain).lower()
    if isinstance(plain, list):
        return "[" + ", ".join(_toml_value(v) for v in plain) + "]"
    return json.dumps(plain)


def replace_block(text: str, block: str) -> str:
    """Replace the content between the generated-block markers.

    Raises:
        ValueError: If the markers are missing or out of order.
    """
    start = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    if start < 0 or end < start:
        msg = f"markers {BEGIN_MARKER!r} / {END_MARKER!r} not found in order"
        raise ValueError(msg)
    head = text[: start + len(BEGIN_MARKER)]
    return f"{head}\n\n{block.strip()}\n\n{text[end:]}"


def _renderers(
    model: type[BaseModel], sections: Sequence[tuple[str, Sequence[str]]]
) -> list[tuple[Path, Callable[[str], str]]]:
    tables = render_tables(model, sections)
    return [
        (DOC_FILE, lambda current: replace_block(current, tables)),
        (ENV_FILE, lambda _current: render_env(model)),
        (TOML_FILE, lambda _current: render_toml(model)),
    ]


def main(
    argv: Sequence[str] | None = None,
    *,
    root_dir: Path = REPO_ROOT,
    model: type[BaseModel] = RoboProbeSettings,
    sections: Sequence[tuple[str, Sequence[str]]] = SECTIONS,
) -> int:
    """Regenerate (or ``--check``) every generated configuration file.

    Args:
        argv: Command-line arguments (default: ``sys.argv[1:]``).
        root_dir: Repository root containing the generated files.
        model: Root settings model (tests pass a tiny one).
        sections: docs/27 §4 headings for ``model``.

    Returns:
        ``0`` when files are (now) up to date, ``1`` when ``--check`` found drift.
    """
    parser = argparse.ArgumentParser(description="Generate docs/27 tables and config templates.")
    parser.add_argument("--check", action="store_true", help="fail on drift, write nothing")
    args = parser.parse_args(argv)
    stale = 0
    for rel, render in _renderers(model, sections):
        path = root_dir / rel
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        expected = render(current)
        if current == expected:
            continue
        if args.check:
            stale += 1
            sys.stderr.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    expected.splitlines(keepends=True),
                    f"{rel.as_posix()} (committed)",
                    f"{rel.as_posix()} (generated)",
                )
            )
        else:
            path.write_text(expected, encoding="utf-8")
            sys.stderr.write(f"updated {rel.as_posix()}\n")
    if stale:
        sys.stderr.write(f"{stale} generated file(s) stale: run `make config-docs`\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
